# This script suggests an outing for a Shih Tzu based on the user's available time.
# It asks for the dog's name and how many minutes the user has right now.

dog_name = input("What is your Shih Tzu's name? ").strip()
minutes = input("How much time, in minutes, do you have right now? ")

try:
    minutes = int(minutes)

    if minutes < 1:
        print(f"You entered {minutes} minutes for {dog_name}. Please enter 1 or more.")
    elif minutes == 1:
        print(f"You have {minutes} minutes right now. Set a reminder to take {dog_name} out for a potty break!")
    elif minutes <= 10:
        print(f"You have {minutes} minutes! Take {dog_name} outside for a quick potty break in the front or backyard.")
    else:
        print(f"You have {minutes} minutes! Take {dog_name} for a walk around the neighborhood.")
except ValueError:
    print("Please enter a valid number for minutes.")


